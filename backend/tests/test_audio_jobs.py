def related(db: Session) -> list[tuple[uuid.UUID, uuid.UUID, str]]:
    return [
        (item.submission_a, item.submission_b, item.relation)
        for item in db.scalars(select(RelatedItem))
    ]


def test_the_same_file_twice_is_flagged_and_linked(
    client: TestClient, speaker_id: str, engine: Engine, db: Session, tmp_path: Path
) -> None:
    content = make_audio(tmp_path / "a", "webm", seconds=2)
    first = submit_audio(client, speaker_id, content)
    run_jobs(engine)
    second = submit_audio(client, speaker_id, content)
    run_jobs(engine)

    one, one_submission = fetch(db, first)
    two, two_submission = fetch(db, second)
    assert one.quality_flags == two.quality_flags == ["possible_duplicate"]
    assert one.upload_status == two.upload_status == "promoted"  # both kept for the reviewer
    pair = sorted([one_submission.id, two_submission.id])
    assert related(db) == [(pair[0], pair[1], "possible_duplicate")]


def test_the_same_sound_in_another_format_is_flagged(
    client: TestClient, speaker_id: str, engine: Engine, db: Session, tmp_path: Path
) -> None:
    first = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "wav", seconds=2))
    second = submit_audio(client, speaker_id, make_audio(tmp_path / "b", "flac", seconds=2))
    third = submit_audio(
        client, speaker_id, make_audio(tmp_path / "c", "flac", source="sine=frequency=330:d=2")
    )
    run_jobs(engine)

    flags = [fetch(db, recording_id)[0].quality_flags for recording_id in (first, second, third)]
    assert flags == [["possible_duplicate"], ["possible_duplicate"], []]
    assert len(related(db)) == 1


def test_checking_again_links_nothing_new(
    client: TestClient, speaker_id: str, engine: Engine, db: Session, tmp_path: Path
) -> None:
    content = make_audio(tmp_path / "a", "mp3", seconds=2)
