def test_derived_copies_are_made_and_traced(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    recording_id = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "m4a", seconds=3))
    run_jobs(engine)

    recording, _ = fetch(db, recording_id)
    made = db.scalars(select(Rendition).where(Rendition.recording_id == recording_id)).all()
    assert sorted(r.kind for r in made) == [
        "analysis_flac_16k_mono",
        "playback_aac",
        "playback_opus",
        "waveform_peaks",
    ]
    run = db.scalars(
        select(ProcessingRun).where(ProcessingRun.job_type == "audio.renditions")
    ).one()
    folder = recording.original_object_key.rsplit("/", 1)[0]
    for rendition in made:
        assert rendition.processing_run_id == run.id
        assert rendition.object_key.startswith(f"{folder}/{rendition.kind}-")
        assert object_store.sha256_of(Bucket.DERIVED, rendition.object_key) == rendition.sha256
        assert rendition.tool_versions["ffmpeg"].startswith("ffmpeg version")
    key = recording.original_object_key
    assert object_store.sha256_of(Bucket.ORIGINALS, key) == recording.sha256_original


