def test_validating_again_changes_nothing(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    recording_id = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "flac"))
    run_jobs(engine)
    before, _ = fetch(db, recording_id)

    queue.enqueue(db, "audio.validate", target_type="recording", target_id=recording_id)
    db.commit()
    run_jobs(engine)

    after, _ = fetch(db, recording_id)
    assert after.upload_status == "promoted"
    assert after.duration_ms == before.duration_ms
    key = after.original_object_key
    assert object_store.sha256_of(Bucket.ORIGINALS, key) == after.sha256_original
    summaries = db.scalars(
        select(ProcessingRun.output_summary)
        .where(ProcessingRun.job_type == "audio.validate")
        .order_by(ProcessingRun.id)
    ).all()
    assert summaries[-1] == {"skipped": "promoted"}


def test_a_copy_left_by_an_interrupted_attempt_is_reused(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    content = make_audio(tmp_path / "a", "mp3")
    recording_id = submit_audio(client, speaker_id, content)
    recording, _ = fetch(db, recording_id)
    with (tmp_path / "a").open("rb") as file:
        object_store.put(Bucket.ORIGINALS, recording.original_object_key, file)
    run_jobs(engine)

    recording, _ = fetch(db, recording_id)
    assert recording.upload_status == "promoted"


def test_a_changed_quarantine_file_is_not_promoted(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    recording_id = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "wav"))
    recording, _ = fetch(db, recording_id)
    make_audio(tmp_path / "b", "wav", seconds=1)
    with (tmp_path / "b").open("rb") as file:
        object_store.delete(Bucket.QUARANTINE, recording.original_object_key)
        object_store.put(Bucket.QUARANTINE, recording.original_object_key, file)
    run_jobs(engine)

    job = db.scalars(select(Job).where(Job.job_type == "audio.validate")).one()
    assert (job.status, job.last_error_code) == ("failed", "checksum_mismatch")
    recording, _ = fetch(db, recording_id)
    assert recording.upload_status == "quarantined"
    assert object_store.head(Bucket.ORIGINALS, recording.original_object_key) is None


