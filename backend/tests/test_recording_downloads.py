ZIP = "/api/v1/me/recordings.zip"


def download_url(recording_id: uuid.UUID) -> str:
    return f"/api/v1/recordings/{recording_id}/download"


def test_file_names_hold_the_day_how_and_what_but_no_title() -> None:
    recording = Recording(id=uuid.UUID("0199f2a1-0000-7000-8000-00003f9a0c21"))
    submission = Submission(
        recorded_on=None,
        submitted_at=datetime(2026, 10, 12, 9, 30, tzinfo=UTC),
        created_at=datetime(2026, 10, 11, tzinfo=UTC),
        title="Asha's story",
        recording_mode="read",
        content_type="sentence_list",
    )
    aac = downloads.DOWNLOAD_KINDS[0]
    name = downloads.file_name(submission, recording, aac)
    assert name == "lokdhara-2026-10-12-read-sentence-list-3f9a0c21.m4a"
    submission.recorded_on = date(2026, 9, 1)
    submission.recording_mode = "free"
    submission.content_type = "story"
    name = downloads.file_name(submission, recording, aac)
    assert name == "lokdhara-2026-09-01-free-story-3f9a0c21.m4a"


