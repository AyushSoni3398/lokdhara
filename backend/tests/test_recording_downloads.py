def submit_audio(client: TestClient, speaker_id: str, content: bytes) -> uuid.UUID:
    draft = create_draft(client, speaker_id)
    response = upload(client, draft["id"], content)
    assert response.status_code == 202, response.text
    assert client.post(f"{SUBMISSIONS}/{draft['id']}/submit").status_code == 200
    return uuid.UUID(response.json()["recording_id"])


def run_jobs(engine: Engine) -> None:
    while queue.process_one(engine, "test-worker", 60):
        pass


def aac_copy(db: Session, store: ObjectStore, recording_id: uuid.UUID) -> bytes:
    rendition = db.scalars(
        select(Rendition).where(
            Rendition.recording_id == recording_id, Rendition.kind == "playback_aac"
        )
    ).one()
    return b"".join(store.open(Bucket.DERIVED, rendition.object_key))


def set_submission(db: Session, recording_id: uuid.UUID, **fields: object) -> None:
    db.expire_all()
    recording = db.get_one(Recording, recording_id)
    submission = db.get_one(Submission, recording.submission_id)
    for field, value in fields.items():
        setattr(submission, field, value)
    db.commit()


def test_the_owner_saves_the_listening_copy(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    recording_id = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "webm", rate=48000))
    response = client.get(download_url(recording_id), follow_redirects=False)
    assert (response.status_code, response.json()["code"]) == (409, "download_not_ready")
    run_jobs(engine)

    response = client.get(download_url(recording_id), follow_redirects=False)
    assert response.status_code == 303
    saved = client.get(response.headers["location"])
    assert saved.status_code == 200
    assert saved.headers["content-type"] == "audio/mp4"
    assert re.fullmatch(
        r'attachment; filename="lokdhara-\d{4}-\d{2}-\d{2}-free-story-[0-9a-f]{8}\.m4a"',
        saved.headers["content-disposition"],
    )
    assert saved.content == aac_copy(db, object_store, recording_id)


def test_nobody_else_can_download_it(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    make_user: MakeUser,
    tmp_path: Path,
) -> None:
    recording_id = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "m4a"))
    run_jobs(engine)

    for name, role in [("ravi", "contributor"), ("meera", "researcher"), ("root", "admin")]:
        act_as(client, make_user(name, role))
        response = client.get(download_url(recording_id), follow_redirects=False)
        assert (response.status_code, response.json()["code"]) == (404, "recording_not_found")
        assert client.get(ZIP).json()["code"] == "no_recordings"
    response = client.get(download_url(uuid.uuid4()), follow_redirects=False)
    assert response.json()["code"] == "recording_not_found"


