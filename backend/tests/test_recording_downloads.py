def test_download_all_zips_every_ready_recording(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    make_user: MakeUser,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    assert client.get(ZIP).json()["code"] == "no_recordings"
    first = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "m4a", seconds=2))
    second = submit_audio(client, speaker_id, make_audio(tmp_path / "b", "ogg", rate=48000))
    run_jobs(engine)
    not_ready = submit_audio(client, speaker_id, make_audio(tmp_path / "c", "m4a"))

    response = client.get(ZIP)
    assert response.status_code == 200
    assert response.headers["content-type"] == "application/zip"
    assert re.fullmatch(
        r'attachment; filename="lokdhara-recordings-\d{4}-\d{2}-\d{2}\.zip"',
        response.headers["content-disposition"],
    )
    archive = zipfile.ZipFile(io.BytesIO(response.content))
    names = archive.namelist()
    assert names.pop() == "details.csv"
    assert [name[-12:-4] for name in names] == [str(first)[-8:], str(second)[-8:]]
    details = list(csv.DictReader(io.StringIO(archive.read("details.csv").decode("utf-8-sig"))))
    assert [row["file"] for row in details] == names
    assert {row["recording_mode"] for row in details} == {"free"}
    assert {row["topics"] for row in details} == {""}
    assert float(details[0]["duration_seconds"]) == 2.0
    assert str(not_ready)[-8:] not in "".join(names)
    for name, recording_id in zip(names, [first, second], strict=True):
        assert archive.read(name) == aac_copy(db, object_store, recording_id)

    # Someone else's recordings never end up in your zip.
    act_as(client, make_user("ravi", "contributor"))
    other = own_speaker(client)
    give_consent(client, db, other)
    submit_audio(client, other, make_audio(tmp_path / "d", "m4a"))
    run_jobs(engine)
    assert len(zipfile.ZipFile(io.BytesIO(client.get(ZIP).content)).namelist()) == 2


def test_a_copy_deleted_meanwhile_is_left_out(
    client: TestClient,
    speaker_id: str,
    engine: Engine,
    db: Session,
    object_store: ObjectStore,
    tmp_path: Path,
) -> None:
    gone = submit_audio(client, speaker_id, make_audio(tmp_path / "a", "m4a"))
    kept = submit_audio(client, speaker_id, make_audio(tmp_path / "b", "m4a"))
    run_jobs(engine)
    for rendition in db.scalars(select(Rendition).where(Rendition.recording_id == gone)):
        object_store.delete(Bucket.DERIVED, rendition.object_key)

    names = zipfile.ZipFile(io.BytesIO(client.get(ZIP).content)).namelist()
    assert names[-1] == "details.csv"
    assert [name[-12:-4] for name in names[:-1]] == [str(kept)[-8:]]
