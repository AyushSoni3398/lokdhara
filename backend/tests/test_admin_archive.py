@pytest.fixture(autouse=True)
def worker_uses_test_storage(
    monkeypatch: pytest.MonkeyPatch, settings: Settings, object_store: ObjectStore
) -> Iterator[None]:
    monkeypatch.setattr(processing, "get_settings", lambda: settings)
    monkeypatch.setattr(processing, "get_object_store", lambda: object_store)
    yield


def run_jobs(engine: Engine) -> None:
    while queue.process_one(engine, "test-worker", 60):
        pass


def submit_audio(client: TestClient, speaker_id: str, content: bytes) -> uuid.UUID:
    draft = create_draft(client, speaker_id)
    response = upload(client, draft["id"], content)
    assert response.status_code == 202, response.text
    assert client.post(f"{SUBMISSIONS}/{draft['id']}/submit").status_code == 200
    return uuid.UUID(response.json()["recording_id"])


def jsonl(archive: zipfile.ZipFile, name: str) -> list[dict[str, Any]]:
    return [json.loads(line) for line in archive.read(name).decode().splitlines()]


@pytest.fixture
def recordings(
    client: TestClient, make_user: MakeUser, db: Session, engine: Engine, tmp_path: Path
) -> dict[uuid.UUID, bytes]:
    """Two recordings by Asha, one of them culturally restricted; an admin stored her name."""
    act_as(client, make_user("asha", "contributor"))
    speaker_id = own_speaker(client)
    give_consent(client, db, speaker_id)
    contents = {}
    for name in ("open", "restricted"):
        content = make_audio(tmp_path / name, "m4a")
        contents[submit_audio(client, speaker_id, content)] = content
    run_jobs(engine)
    restricted = db.get_one(Recording, list(contents)[1])
    db.get_one(Submission, restricted.submission_id).restriction_flags = ["culturally_restricted"]
    db.commit()

    act_as(client, make_user("root", "admin"))
    identity = {"full_name": "Synthetic Name", "contact": "000-TEST", "village": "Test Village"}
    response = client.put(f"/api/v1/speakers/{speaker_id}/identity", json=identity)
    assert response.status_code == 200, response.text
    return contents


def test_the_archive_holds_everything(
    client: TestClient, recordings: dict[uuid.UUID, bytes], db: Session
) -> None:
    response = client.get(ARCHIVE, params=REASON)
    assert response.status_code == 200, response.text
    assert response.headers["content-type"] == "application/zip"
    assert re.fullmatch(
        r'attachment; filename="lokdhara-archive-\d{4}-\d{2}-\d{2}T\d{6}Z\.zip"',
        response.headers["content-disposition"],
    )
    archive = zipfile.ZipFile(io.BytesIO(response.content))
    assert archive.testzip() is None
    assert REASON["reason"] in archive.read("README.txt").decode()

    # Every original, byte for byte, restricted or not.
    for recording_id, content in recordings.items():
        assert archive.read(f"originals/{recording_id}.m4a") == content
    files = jsonl(archive, "files.jsonl")
    assert [f["stored"] for f in files if f["bucket"] == "originals"] == [True, True]

    submissions = jsonl(archive, "data/submissions.jsonl")
    assert sorted(s["restriction_flags"] for s in submissions) == [[], ["culturally_restricted"]]
    assert {r["id"] for r in jsonl(archive, "data/recordings.jsonl")} == {
        str(r) for r in recordings
    }
    [identity] = jsonl(archive, "data/speaker_identities.jsonl")
    assert (identity["full_name"], identity["contact"]) == ("Synthetic Name", "000-TEST")

    # Sign-in secrets never leave.
    users = jsonl(archive, "data/users.jsonl")
    assert {u["username"] for u in users} == {"asha", "root"}
    assert all("password_hash" not in u for u in users)

    event = db.scalars(select(AuditEvent).where(AuditEvent.action == "archive.download")).one()
    assert event.details == {"reason": REASON["reason"], "files": 2}


def test_a_missing_file_is_listed_not_fatal(
    client: TestClient,
    recordings: dict[uuid.UUID, bytes],
    db: Session,
    object_store: ObjectStore,
) -> None:
    gone = db.get_one(Recording, next(iter(recordings)))
    object_store.erase(Bucket.ORIGINALS, gone.original_object_key)

    archive = zipfile.ZipFile(io.BytesIO(client.get(ARCHIVE, params=REASON).content))
    assert f"originals/{gone.id}.m4a" not in archive.namelist()
    stored = {f["name"]: f["stored"] for f in jsonl(archive, "files.jsonl")}
    assert stored[f"originals/{gone.id}.m4a"] is False


def test_a_reason_is_required(client: TestClient, make_user: MakeUser, db: Session) -> None:
    act_as(client, make_user("root", "admin"))
    assert client.get(ARCHIVE).status_code == 422
    assert client.get(ARCHIVE, params={"reason": "short"}).status_code == 422
    assert db.scalar(select(AuditEvent).where(AuditEvent.action == "archive.download")) is None


