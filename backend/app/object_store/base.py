"""ObjectStore interface (ADR-006). Callers never see bucket names, paths, or credentials.

Object keys are generated by the server and contain only UUIDs and fixed words, never names or
client filenames (docs/PRIVACY_AND_SECURITY.md).
"""

import hashlib
import re
import uuid
from abc import ABC, abstractmethod
from collections.abc import Iterator
from dataclasses import dataclass
from enum import StrEnum
from typing import Protocol

CHUNK_SIZE = 1024 * 1024
_KEY_PATTERN = re.compile(r"^[a-z0-9][a-z0-9_-]*(/[a-z0-9][a-z0-9_.-]*)*$")


class Readable(Protocol):
    def read(self, size: int = -1, /) -> bytes: ...


class Bucket(StrEnum):
    """Storage classes separated by sensitivity; each maps to its own bucket."""

    QUARANTINE = "quarantine"
    ORIGINALS = "originals"
    DERIVED = "derived"
    CONSENT_EVIDENCE = "consent_evidence"
    EXPORTS = "exports"


# Originals and consent evidence are written once and never overwritten (ADR-009).
WRITE_ONCE = frozenset({Bucket.ORIGINALS, Bucket.CONSENT_EVIDENCE})
# Only these may be handed out as signed download URLs (docs/ACCESS_CONTROL.md §4).
SIGNABLE = frozenset({Bucket.DERIVED, Bucket.EXPORTS})


class StorageError(Exception):
    """Base class; messages never include object contents."""


class ObjectNotFound(StorageError):
    pass


class ObjectExists(StorageError):
    """A write-once bucket already holds this key."""


class ObjectTooLarge(StorageError):
    pass


class IntegrityError(StorageError):
    """Bytes read back do not match the expected SHA-256."""


@dataclass(frozen=True)
class StoredObject:
    key: str
    size_bytes: int
    sha256: str


def attachment_header(download_name: str) -> str:
    """A Content-Disposition value; names are made by the app, but keep them to safe characters."""
    if not re.fullmatch(r"[A-Za-z0-9._-]{1,100}", download_name):
        raise ValueError("download names may only use letters, digits, '.', '_' and '-'")
    return f'attachment; filename="{download_name}"'


def validate_key(key: str) -> str:
    if len(key) > 512 or ".." in key or not _KEY_PATTERN.fullmatch(key):
        raise ValueError("invalid object key")
    return key


def new_key(*parts: str | uuid.UUID, suffix: str = "") -> str:
    """Builds a key from fixed words and UUIDs, e.g. new_key("recordings", rid, suffix=".webm")."""
    key = "/".join(str(part) for part in parts) + suffix
    return validate_key(key)


class _HashingReader:
    """Wraps a stream, hashing and counting bytes as they are read, enforcing a size cap."""

    def __init__(self, stream: Readable, max_bytes: int | None) -> None:
        self._stream = stream
        self._max_bytes = max_bytes
        self.size = 0
        self._hash = hashlib.sha256()

    def read(self, size: int = -1, /) -> bytes:
        # Reads at most one chunk when size is negative; callers loop until b"".
        data = self._stream.read(size if size > 0 else CHUNK_SIZE)
        self.size += len(data)
        if self._max_bytes is not None and self.size > self._max_bytes:
            raise ObjectTooLarge(f"object exceeds {self._max_bytes} bytes")
        self._hash.update(data)
        return data

    @property
    def sha256(self) -> str:
        return self._hash.hexdigest()


class ObjectStore(ABC):
    @abstractmethod
    def put(
        self,
        bucket: Bucket,
        key: str,
        stream: Readable,
        *,
        content_type: str = "application/octet-stream",
        max_bytes: int | None = None,
    ) -> StoredObject:
        """Streams `stream` into storage, returning its size and SHA-256.

        Raises ObjectTooLarge (nothing is kept) or, for write-once buckets, ObjectExists.
        """

    @abstractmethod
    def open(self, bucket: Bucket, key: str) -> Iterator[bytes]:
        """Yields the object's bytes in chunks. Raises ObjectNotFound."""

    @abstractmethod
    def head(self, bucket: Bucket, key: str) -> int | None:
        """Size in bytes, or None if the object does not exist."""

    @abstractmethod
    def delete(self, bucket: Bucket, key: str) -> None:
        """Only quarantine and export cleanup and the erasure routine call this. Missing keys are
        ignored."""

    @abstractmethod
    def erase(self, bucket: Bucket, key: str) -> None:
        """Deletes the object and, in versioned buckets, every earlier version of it. Only the
        withdrawal routine calls this (docs/DATA_RETENTION_AND_DELETION.md §2). Missing keys
        are ignored."""

    @abstractmethod
    def signed_url(
        self,
        bucket: Bucket,
        key: str,
        *,
        ttl_seconds: int,
        content_type: str,
        download_name: str | None = None,
    ) -> str:
        """Short-lived download URL. Only for derived playback files and exports.

        With `download_name` the file is served as an attachment with that name, so a browser
        saves it instead of opening it (docs/PRIVACY_AND_SECURITY.md §4).
        """

    @abstractmethod
    def is_reachable(self) -> bool:
        """For /readyz: can every configured bucket be reached?"""

    def sha256_of(self, bucket: Bucket, key: str) -> str:
        digest = hashlib.sha256()
        for chunk in self.open(bucket, key):
            digest.update(chunk)
        return digest.hexdigest()

    def copy_verified(
        self,
        src_bucket: Bucket,
        src_key: str,
        dst_bucket: Bucket,
        dst_key: str,
        expected_sha256: str,
    ) -> StoredObject:
        """Copies an object (e.g. quarantine → originals) and proves the copy is byte-identical."""
        if self.sha256_of(src_bucket, src_key) != expected_sha256:
            raise IntegrityError("source does not match the expected checksum")
        stored = self.put(dst_bucket, dst_key, _ChunkStream(self.open(src_bucket, src_key)))
        if (
            stored.sha256 != expected_sha256
            or self.sha256_of(dst_bucket, dst_key) != expected_sha256
        ):
            raise IntegrityError("copy does not match the expected checksum")
        return stored


class _ChunkStream:
    """Adapts a chunk iterator to the minimal file-like read() that put() needs."""

    def __init__(self, chunks: Iterator[bytes]) -> None:
        self._chunks = chunks
        self._buffer = b""

    def read(self, size: int = -1, /) -> bytes:
        while size < 0 or len(self._buffer) < size:
            try:
                self._buffer += next(self._chunks)
            except StopIteration:
                break
        if size < 0:
            data, self._buffer = self._buffer, b""
        else:
            data, self._buffer = self._buffer[:size], self._buffer[size:]
        return data
